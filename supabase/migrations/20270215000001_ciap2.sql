  capitulo        text NOT NULL CHECK (capitulo ~ '^[A-Z]$'),
  cid10_relacionada text,
  busca           tsvector GENERATED ALWAYS AS (
    to_tsvector('portuguese', terminologia.unaccent_text(coalesce(descricao, '')))
