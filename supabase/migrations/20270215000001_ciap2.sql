-- ── 1. busca ────────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION pg_temp.ciap_trocar(p_f regprocedure, VARIADIC p_pares text[])
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  def text := replace(pg_get_functiondef(p_f), chr(13), '');
  novo text := def;
BEGIN
  FOR k IN 1 .. array_length(p_pares, 1) BY 2 LOOP
    CONTINUE WHEN position(p_pares[k + 1] IN novo) > 0;
    IF position(p_pares[k] IN novo) = 0 THEN
      RAISE EXCEPTION '% mudou: trecho não encontrado: %', p_f, p_pares[k];
    END IF;
    novo := replace(novo, p_pares[k], p_pares[k + 1]);
  END LOOP;
  IF novo <> def THEN EXECUTE novo; END IF;
END $$;

SELECT pg_temp.ciap_trocar('terminologia.buscar(text, text, integer)',
  '  -- ── SIGTAP ',
  '  -- ── CIAP-2 (5A, tarefa 4) ──
  IF p_tabela = ''ciap2'' THEN
    RETURN QUERY
      SELECT ''ciap2''::text, t.codigo, t.descricao,
             jsonb_build_object(''capitulo'', t.capitulo, ''cid10'', t.cid10_relacionada),
             ts_rank(t.busca, v_query)
      FROM terminologia.ciap2 t
      WHERE t.busca @@ v_query OR t.codigo ILIKE (terminologia.unaccent_text(trim(p_termo)) || ''%'')
      ORDER BY (t.codigo ILIKE (terminologia.unaccent_text(trim(p_termo)) || ''%'')) DESC, rank DESC, t.codigo
      LIMIT p_limite;
    RETURN;
  END IF;

  -- ── SIGTAP ');

CREATE OR REPLACE FUNCTION pg_temp.ciap_exigir_troca(p_def text, p_antigo text, p_novo text)
RETURNS text LANGUAGE plpgsql AS $$
BEGIN
  IF position(p_antigo IN p_def) = 0 THEN RAISE EXCEPTION 'registrar_conduta_aps mudou: trecho não encontrado: %', p_antigo; END IF;
  RETURN replace(p_def, p_antigo, p_novo);
END $$;

-- ── 2. episódio ─────────────────────────────────────────────────────────────
ALTER TABLE public.episodios ADD COLUMN IF NOT EXISTS ciap_aps text[];
COMMENT ON COLUMN public.episodios.ciap_aps IS
  'Problema/condição avaliada em CIAP-2 (tabela do LEDI do e-SUS APS), na conduta da consulta da UBS.';

-- ── 3. conduta com a CIAP-2 ─────────────────────────────────────────────────
DO $$
DECLARE def text;
BEGIN
  IF to_regprocedure('public.registrar_conduta_aps(uuid, text, text[], text[], text[], text, text[])') IS NOT NULL THEN
    RETURN;  -- já aplicada
  END IF;
  def := replace(pg_get_functiondef('public.registrar_conduta_aps(uuid, text, text[], text[], text[], text)'::regprocedure), chr(13), '');
  def := pg_temp.ciap_exigir_troca(def,
    'p_condutas text[], p_obs text DEFAULT NULL::text)',
    'p_condutas text[], p_obs text DEFAULT NULL::text, p_ciaps text[] DEFAULT NULL::text[])');
  def := pg_temp.ciap_exigir_troca(def,
    '  v_cids text[] := ''{}'';',
    '  v_cids text[] := ''{}'';
  v_ciaps text[] := ARRAY(SELECT DISTINCT upper(btrim(x)) FROM unnest(coalesce(p_ciaps, ''{}'')) x WHERE nullif(btrim(x), '''') IS NOT NULL ORDER BY 1);');
  def := pg_temp.ciap_exigir_troca(def,
    '  IF cardinality(v_prob) + cardinality(v_cids) = 0 THEN
    RAISE EXCEPTION ''Informe ao menos um problema ou condição avaliada (lista da ficha ou CID-10).'';',
    '  IF EXISTS (SELECT 1 FROM unnest(v_ciaps) x WHERE NOT EXISTS (SELECT 1 FROM terminologia.ciap2 t WHERE t.codigo = x)) THEN
    RAISE EXCEPTION ''CIAP-2 não encontrada na tabela do e-SUS APS: %.'',
      (SELECT string_agg(x, '', '') FROM unnest(v_ciaps) x WHERE NOT EXISTS (SELECT 1 FROM terminologia.ciap2 t WHERE t.codigo = x));
  END IF;
  IF cardinality(v_prob) + cardinality(v_cids) + cardinality(v_ciaps) = 0 THEN
    RAISE EXCEPTION ''Informe ao menos um problema ou condição avaliada (lista da ficha, CIAP-2 ou CID-10).'';');
  def := pg_temp.ciap_exigir_troca(def,
    'problemas_aps = v_prob, cid_aps = v_cids,',
    'problemas_aps = v_prob, cid_aps = v_cids, ciap_aps = v_ciaps,');
  EXECUTE def;
  DROP FUNCTION public.registrar_conduta_aps(uuid, text, text[], text[], text[], text);
END $$;
REVOKE ALL ON FUNCTION public.registrar_conduta_aps(uuid, text, text[], text[], text[], text, text[]) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.registrar_conduta_aps(uuid, text, text[], text[], text[], text, text[]) TO authenticated;

